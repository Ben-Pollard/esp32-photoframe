#!/usr/bin/env python3
"""Generate main/prompt_template_default.h from ai-lab/prompt_template.md.

The device and the lab must send the same prompt, and the only way to be sure of
that is to derive one from the other rather than maintain two copies by hand.
The template is authored in the lab; this writes it into the firmware as a C
string, and `--check` fails if the committed header is stale.

The template's '#!' notes are dropped and the <<<SYSTEM / <<<USER seam is joined
with a blank line, exactly as exp.py's load_template() does, so the text that
reaches the model is identical on both sides.

    ./gen_prompt_template.py            rewrite the header
    ./gen_prompt_template.py --check    exit 1 if the header does not match
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "docs", "prompt_template.md")
OUT = os.path.join(REPO, "main", "prompt_template_default.h")
SPLIT_SYSTEM = "<<<SYSTEM"
SPLIT_USER = "<<<USER"


def template_body():
    raw = open(SRC).read()
    body = "\n".join(l for l in raw.splitlines() if not l.startswith("#!"))
    if SPLIT_SYSTEM in body and SPLIT_USER in body:
        head, tail = body.split(SPLIT_SYSTEM, 1)[1].split(SPLIT_USER, 1)
        return (head.strip() + "\n\n" + tail.strip()).strip()
    return body.strip()


def c_literal(text):
    """Escape for a C string, splitting on newlines so the generated file stays
    readable and a diff shows which line of the template changed."""
    out = []
    for line in text.split("\n"):
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'    "{esc}\\n"')
    return "\n".join(out)


def render(body):
    return (
        "// GENERATED by scripts/gen_prompt_template.py -- do not edit by hand.\n"
        "// Source of truth: docs/prompt_template.md. Run the generator after\n"
        "// changing the template; `--check` fails if this file is stale.\n"
        "#pragma once\n\n"
        "// The whole prompt, sent as a single user message. {{weather}} is replaced\n"
        "// with the day's data block before sending.\n"
        "static const char PROMPT_TEMPLATE_DEFAULT[] =\n"
        + c_literal(body) + ";\n"
    )


def main():
    body = template_body()
    want = render(body)
    if "--check" in sys.argv:
        have = open(OUT).read() if os.path.exists(OUT) else ""
        if have != want:
            print("main/prompt_template_default.h is stale -- run "
                  "scripts/gen_prompt_template.py")
            sys.exit(1)
        print("prompt_template_default.h matches docs/prompt_template.md")
        return
    with open(OUT, "w") as f:
        f.write(want)
    print(f"wrote {OUT} ({len(body)} chars of template)")


if __name__ == "__main__":
    main()
