#!/usr/bin/env python3
"""Generate main/label_font.h -- a bitmap font for the on-panel date label.

The overlay is drawn after dithering, in one flat ink, so it must be already
rasterised: no font rendering, no anti-aliasing, no scaling on the device. This
bakes ASCII 32..126 from a system monospace face into 1-bit rows.

Monospace is deliberate: a fixed cell keeps the blitter trivial, and the label is
a fixed-format string ("20th Nov | Clear sky"), not prose.

    ./gen_label_font.py            write the header
    ./gen_label_font.py --check    exit 1 if the header is stale
    ./gen_label_font.py --preview  also write /tmp/label_preview.png
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "main", "label_font.h")
FONT_PATH = "/usr/share/fonts/adwaita-mono-fonts/AdwaitaMono-Bold.ttf"
SIZE = 20
FIRST, LAST = 32, 126


def rasterise():
    """Rasterise every glyph into a SHARED cell with a shared baseline.

    The first version cropped each glyph to its own bounding box, which threw
    away the baseline: 'o' and 'v' have no ascender, so they were pinned to the
    top of the cell and read as superscript against 'N' and 'F'. Drawing each
    glyph at the same baseline anchor keeps their relative positions.
    """
    font = ImageFont.truetype(FONT_PATH, SIZE)
    ascent, descent = font.getmetrics()
    w = int(round(font.getlength("M")))
    h = ascent + descent
    cells = {}
    for code in range(FIRST, LAST + 1):
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((0, ascent), chr(code), font=font, anchor="ls", fill=255)
        cells[code] = img
    return font, cells, w, h


def bitmap(img, w, h):
    rows = []
    for y in range(h):
        bits = 0
        for x in range(w):
            if img.getpixel((x, y)) > 127:
                bits |= 1 << x
        rows.append(bits)
    return rows


def render(w, h):
    _, cells, _, _ = rasterise()
    glyphs = [(code, bitmap(cells[code], w, h)) for code in range(FIRST, LAST + 1)]
    lines = [
        "// GENERATED by scripts/gen_label_font.py -- do not edit by hand.",
        f"// {os.path.basename(FONT_PATH)} at {SIZE}px, ASCII {FIRST}..{LAST}.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define LABEL_FONT_W {w}",
        f"#define LABEL_FONT_H {h}",
        f"#define LABEL_FONT_FIRST {FIRST}",
        f"#define LABEL_FONT_LAST {LAST}",
        "",
        "// One uint16 per row, bit x = pixel x.",
        f"static const uint16_t LABEL_FONT[{LAST - FIRST + 1}][LABEL_FONT_H] = {{",
    ]
    for code, rows in glyphs:
        ch = chr(code)
        label = "space" if ch == " " else ("pipe" if ch == "|" else ch)
        body = ", ".join("0x%04x" % r for r in rows)
        lines.append(f"    {{{body}}},  // '{label}'")
    lines.append("};")
    lines.append("")
    return "\n".join(lines), glyphs


def preview(glyphs, w, h):
    text = "20th Nov | Clear sky"
    img = Image.new("L", (w * len(text) + 8, h + 8), 255)
    px = img.load()
    for i, ch in enumerate(text):
        rows = dict(glyphs).get(ord(ch))
        if rows is None:
            continue
        for y in range(h):
            for x in range(w):
                if rows[y] & (1 << x):
                    px[i * w + x + 4, y + 4] = 0
    img = img.resize((img.width * 3, img.height * 3), Image.NEAREST)
    img.save("/tmp/label_preview.png")
    print("preview -> /tmp/label_preview.png (%dx%d per glyph)" % (w, h))


def main():
    text, glyphs = render(*rasterise()[2:])
    if "--check" in sys.argv:
        have = open(OUT).read() if os.path.exists(OUT) else ""
        if have != text:
            print("main/label_font.h is stale -- run scripts/gen_label_font.py")
            sys.exit(1)
        print("label_font.h matches the generator")
        return
    open(OUT, "w").write(text)
    print(f"wrote {OUT}")
    if "--preview" in sys.argv:
        preview(glyphs, *rasterise()[2:])


if __name__ == "__main__":
    main()
